NOTE = (
    "보건복지부 전공의 모집 공고의 약칭을 기관 정식 명칭에 잇는 표. "
    "모집 단위는 기관과 다르다. 통합수련 기관은 한 단위에 여러 병원이 묶이고, "
    "예방의학과는 병원이 아니라 의과대학이 모집 단위다."
)


def main() -> int:
    units: dict[tuple[str, str], set[str]] = {}
    for fname, track in (
        ("recruit_2026h2_intern.json", "인턴"),
        ("recruit_2026h2_resident.json", "레지던트"),
    ):
        payload = json.load(io.open(os.path.join(ROOT, ".cache", "extracted", fname), encoding="utf-8"))
        for r in payload["records"]:
            if "_unparsed" in r:
                continue
            units.setdefault((r["region"], r["hospitalRaw"]), set()).add(track)

    missing = sorted(k for k in units if k not in MAPPING)
    stale = sorted(k for k in MAPPING if k not in units)
    if missing or stale:
        print(f"  !! 공고에 있으나 표에 없는 단위 {len(missing)}: {missing}")
        print(f"  !! 표에만 있고 공고에 없는 단위 {len(stale)}: {stale}")
        return 1

    taken: set[str] = set()
    rows = []
    for (region, raw), tracks in sorted(units.items()):
        names = MAPPING[(region, raw)]
        hospitals = [n for n in names if not n.startswith("@ms:")]
        schools = [n[4:] for n in names if n.startswith("@ms:")]
        rows.append(
            {
                "id": slug("tu", core(raw) or raw, taken),
                "region": region,
                "rawName": raw,
                "name": names[0].replace("@ms:", "") if len(names) == 1 else raw,
                "tracks": sorted(tracks),
                "hospitals": hospitals,
                "medicalSchools": schools,
                "integratedTraining": len(names) > 1,
            }
        )

    dest = os.path.join(ROOT, "data", "curation", "training-units.json")
    doc = {
        "_note": NOTE,
        "_sources": ["src-mohw-recruit-2026h2-intern", "src-mohw-recruit-2026h2-resident"],
        "_checked": "2026-10-29",
        "units": rows,
    }
    json.dump(doc, io.open(dest, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    integrated = sum(1 for r in rows if r["integratedTraining"])
    school_units = sum(1 for r in rows if r["medicalSchools"])
    print(f"  {len(rows)}개 단위 (통합수련 {integrated}, 의과대학 단위 {school_units}) → {dest}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
